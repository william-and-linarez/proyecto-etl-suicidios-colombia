import pandas as pd


def clean_column_names(df: pd.DataFrame) -> pd.DataFrame:
    """
    Elimina espacios innecesarios al inicio y final de los nombres
    de las columnas.
    """
    df = df.copy()
    df.columns = df.columns.str.strip()

    return df

def filter_valid_departments(df: pd.DataFrame) -> pd.DataFrame:
    """
    Excluye los registros cuyo código DANE de departamento es 999,
    utilizado por la fuente para representar 'Sin información'.
    """
    df = df.copy()

    return df[df["Código Dane Departamento"] != 999].copy()

def filter_population_period(
    df_pob1: pd.DataFrame,
    df_pob2: pd.DataFrame
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Conserva únicamente el área geográfica Total y los años
    correspondientes al periodo de estudio 2015-2024.
    """

    pob1 = df_pob1[
        (df_pob1["ÁREA GEOGRÁFICA"] == "Total") &
        (df_pob1["AÑO"].between(2015, 2017))
    ].copy()

    pob2 = df_pob2[
        (df_pob2["ÁREA GEOGRÁFICA"] == "Total") &
        (df_pob2["AÑO"].between(2018, 2024))
    ].copy()

    return pob1, pob2

def reshape_population_2005_2017(
    df: pd.DataFrame
) -> pd.DataFrame:
    """
    Convierte la población DANE 2005-2017 de formato ancho a largo.

    Resultado:
    DP | AÑO | sexo | edad | poblacion
    """

    df = df.copy()

    columnas_edad = [
        c for c in df.columns
        if c.startswith("Hombres_") or c.startswith("Mujeres_")
    ]

    largo = df.melt(
        id_vars=["DP", "AÑO"],
        value_vars=columnas_edad,
        var_name="columna_edad",
        value_name="poblacion"
    )

    largo["sexo"] = (
        largo["columna_edad"]
        .str.split("_")
        .str[0]
        .map({
            "Hombres": "Hombre",
            "Mujeres": "Mujer"
        })
    )

    largo["edad"] = (
        largo["columna_edad"]
        .str.extract(r"(\d+)")[0]
        .astype(int)
    )

    largo = largo[
        ["DP", "AÑO", "sexo", "edad", "poblacion"]
    ]

    return largo

